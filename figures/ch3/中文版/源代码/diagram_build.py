def estw(t,s): return sum(s*(0.55 if ord(c)<128 else 1.0) for c in t)
def _allspans(page):
    out=[]
    for b in page.get_text("dict")["blocks"]:
        for l in b.get("lines",[]):
            for s in l["spans"]:
                if s["text"].strip(): out.append(s["bbox"])
    return out
def build(src,out,R,L=[],EX=[]):
    d=fitz.open(src); p=d[0]; W,H=p.rect.width,p.rect.height
    sp=_allspans(p)
    def snap(rect):  # union bbox of spans: x-center inside rect AND vertical overlap -> true English extent
        x0,y0,x1,y1=rect
        c=[b for b in sp if x0<=(b[0]+b[2])/2<=x1 and b[1]<y1 and b[3]>y0]
        if not c: return None
        return (min(b[0] for b in c),min(b[1] for b in c),max(b[2] for b in c),max(b[3] for b in c))
    place=[]
    for r in R:
        u=snap(r[:4]) or r[:4]
        p.add_redact_annot(fitz.Rect(u[0]-1,u[1]-1,u[2]+1,u[3]+1),fill=None,cross_out=False)
        place.append(((u[0]+u[2])/2,(u[1]+u[3])/2, r[2]-r[0], r[4],r[5],r[6]))
    for r in L:
        u=snap(r[:4]) or r[:4]
        p.add_redact_annot(fitz.Rect(u[0]-1,u[1]-1,u[2]+1,u[3]+1),fill=None,cross_out=False)
    for r in EX: p.add_redact_annot(fitz.Rect(*r),fill=None,cross_out=False)
    p.apply_redactions(images=fitz.PDF_REDACT_IMAGE_NONE, graphics=fitz.PDF_REDACT_LINE_ART_NONE)
    bg=out+".bg.pdf"; d.save(bg,garbage=4,deflate=True,clean=True)
    fig=plt.figure(figsize=(W/72,H/72)); ax=fig.add_axes([0,0,1,1]); ax.set_xlim(0,W); ax.set_ylim(H,0); ax.axis('off')
    for (cx,cy,ow,zh,size,bold) in place:
        s=size
        while s>4.5 and estw(zh,s)>ow*1.02: s-=0.3
        ax.text(cx,cy,zh,ha='center',va='center',
                fontproperties=(figstyle.propB if bold else figstyle.propR),fontsize=s,color='black')
    for (x0,y0,x1,y1,items,size) in L:
        step=(y1-y0)/len(items)
        for i,it in enumerate(items):
            ax.text(x0,y0+step*(i+0.5),it,ha='left',va='center',fontproperties=figstyle.propR,fontsize=size,color='black')
    tx=out+".txt.pdf"; fig.savefig(tx,transparent=True); plt.close(fig)
    b=fitz.open(bg); t=fitz.open(tx); b[0].show_pdf_page(b[0].rect,t,0); b.save(out,garbage=4,deflate=True,clean=True)
    os.remove(bg); os.remove(tx); print("saved",os.path.basename(out),round(os.path.getsize(out)/1e6,3),"MB")

